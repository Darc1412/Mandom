'use strict';
// 设置读写。默认值 + data/settings.json 覆盖。

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DATA = path.join(ROOT, 'data');
const TOOLS = path.join(ROOT, 'tools');
const COOKIES = path.join(ROOT, 'cookies');

const DEFAULTS = {
  port: 8792,
  outDir: path.join(ROOT, 'downloads'),
  concurrency: 2,
  maxRetries: 2,
  cookiesMode: 'none',            // none | browser | file
  cookiesBrowser: 'edge',
  cookiesFile: '',
  namingTemplate: '{author}_{date}_{id}_{title}',
  autoStart: true,
  probeTimeoutMs: 40000,
  downloadTimeoutMs: 0,            // 0 = 不限
  referer: '',
  userAgent: '',
};

const state = Object.assign({}, DEFAULTS);
let saveTimer = null;

function file() { return path.join(DATA, 'settings.json'); }

function load() {
  try {
    const raw = fs.readFileSync(file(), 'utf8');
    Object.assign(state, DEFAULTS, JSON.parse(raw));
  } catch { /* 首次运行没有文件 */ }
  return state;
}

function saveNow() {
  try {
    fs.mkdirSync(DATA, { recursive: true });
    fs.writeFileSync(file(), JSON.stringify(state, null, 2), 'utf8');
  } catch (e) {
    console.error('[config] 保存失败', e.message);
  }
}

function get() { return state; }

function set(patch) {
  Object.assign(state, patch);
  clearTimeout(saveTimer);
  saveTimer = setTimeout(saveNow, 300);
  return state;
}

function tool(name) {
  const map = {
    ytdlp: 'yt-dlp.exe',
    gallerydl: 'gallery-dl.exe',
    ffmpeg: 'ffmpeg.exe',
    ffprobe: 'ffprobe.exe',
  };
  return path.join(TOOLS, map[name] || name);
}

function toolExists(name) {
  try { return fs.statSync(tool(name)).size > 1024; } catch { return false; }
}

function cookiesDir() {
  fs.mkdirSync(COOKIES, { recursive: true });
  return COOKIES;
}

// 把 cookies/twitter.txt（JSON 或 Netscape 都行）转成 yt-dlp 能吃的 Netscape 文件。
// 没有 twitter.txt 时返回空串。
function netscapeCookieFile() {
  const src = path.join(COOKIES, 'twitter.txt');
  if (!fs.existsSync(src)) return '';
  let raw;
  try { raw = fs.readFileSync(src, 'utf8').trim(); } catch { return ''; }
  if (!raw) return '';

  if (!raw.startsWith('[') && !raw.startsWith('{')) return src; // 已经是 Netscape

  let items;
  try {
    const parsed = JSON.parse(raw);
    items = Array.isArray(parsed) ? parsed : (parsed.cookies || []);
  } catch {
    return '';
  }

  const lines = ['# Netscape HTTP Cookie File', '# generated by collector'];
  for (const c of items) {
    if (!c || !c.name || c.value === undefined) continue;
    const domain = String(c.domain || '');
    if (!/(^|\.)(x|twitter)\.com$/i.test(domain)) continue;
    const includeSub = domain.startsWith('.') ? 'TRUE' : 'FALSE';
    const expires = c.expirationDate ? Math.floor(c.expirationDate) : 0;
    lines.push([
      domain, includeSub, c.path || '/', c.secure ? 'TRUE' : 'FALSE',
      expires, c.name, c.value,
    ].join('\t'));
  }
  if (lines.length <= 2) return '';

  const out = path.join(COOKIES, '_x_for_ytdlp.txt');
  try {
    fs.writeFileSync(out, lines.join('\n') + '\n', 'utf8');
    return out;
  } catch {
    return '';
  }
}

function ensureOutDir() {
  const d = state.outDir;
  fs.mkdirSync(d, { recursive: true });
  return d;
}

module.exports = {
  ROOT, DATA, TOOLS, COOKIES, DEFAULTS,
  load, get, set, saveNow, tool, toolExists, cookiesDir, ensureOutDir,
  netscapeCookieFile,
};
